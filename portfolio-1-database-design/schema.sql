BEGIN;

CREATE TABLE customers (
                           customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           email VARCHAR(254) NOT NULL UNIQUE,
                           first_name VARCHAR(80) NOT NULL,
                           last_name VARCHAR(80) NOT NULL,
                           phone VARCHAR(30),
                           created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE customer_addresses (
                                    address_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    customer_id BIGINT NOT NULL
                                        REFERENCES customers(customer_id) ON DELETE CASCADE,
                                    address_label VARCHAR(40) NOT NULL DEFAULT 'Home',
                                    recipient_name VARCHAR(160) NOT NULL,
                                    phone VARCHAR(30) NOT NULL,
                                    street VARCHAR(240) NOT NULL,
                                    city VARCHAR(100) NOT NULL,
                                    state VARCHAR(100) NOT NULL,
                                    country_code CHAR(2) NOT NULL DEFAULT 'NG',
                                    is_default BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE vendors (
                         vendor_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         business_name VARCHAR(160) NOT NULL,
                         email VARCHAR(254) NOT NULL UNIQUE,
                         status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
                             CHECK (status IN ('ACTIVE', 'SUSPENDED', 'CLOSED')),
                         created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE categories (
                            category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            parent_category_id BIGINT REFERENCES categories(category_id),
                            category_name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE products (
                          product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          vendor_id BIGINT NOT NULL REFERENCES vendors(vendor_id),
                          category_id BIGINT NOT NULL REFERENCES categories(category_id),
                          sku VARCHAR(60) NOT NULL UNIQUE,
                          product_name VARCHAR(180) NOT NULL,
                          description TEXT,
                          unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
                          currency CHAR(3) NOT NULL DEFAULT 'NGN',
                          attributes JSONB NOT NULL DEFAULT '{}'::jsonb,
                          is_active BOOLEAN NOT NULL DEFAULT TRUE,
                          created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                          updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE product_images (
                                image_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                product_id BIGINT NOT NULL
                                    REFERENCES products(product_id) ON DELETE CASCADE,
                                image_url TEXT NOT NULL,
                                display_order SMALLINT NOT NULL DEFAULT 0
);

CREATE TABLE inventory (
                           product_id BIGINT PRIMARY KEY
                               REFERENCES products(product_id) ON DELETE CASCADE,
                           quantity_on_hand INTEGER NOT NULL DEFAULT 0
                               CHECK (quantity_on_hand >= 0),
                           quantity_reserved INTEGER NOT NULL DEFAULT 0
                               CHECK (quantity_reserved >= 0),
                           updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                           CHECK (quantity_reserved <= quantity_on_hand)
);

CREATE TABLE carts (
                       cart_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       customer_id BIGINT NOT NULL REFERENCES customers(customer_id),
                       status VARCHAR(20) NOT NULL DEFAULT 'OPEN'
                           CHECK (status IN ('OPEN', 'CHECKED_OUT', 'ABANDONED')),
                       created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE cart_items (
                            cart_id BIGINT NOT NULL REFERENCES carts(cart_id) ON DELETE CASCADE,
                            product_id BIGINT NOT NULL REFERENCES products(product_id),
                            quantity INTEGER NOT NULL CHECK (quantity > 0),
                            PRIMARY KEY (cart_id, product_id)
);

CREATE TABLE orders (
                        order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        order_number VARCHAR(40) NOT NULL UNIQUE,
                        customer_id BIGINT NOT NULL REFERENCES customers(customer_id),
                        delivery_address_id BIGINT REFERENCES customer_addresses(address_id),
                        order_status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
                            CHECK (order_status IN (
                                                    'PENDING', 'PAID', 'PROCESSING', 'SHIPPED',
                                                    'DELIVERED', 'CANCELLED', 'REFUNDED'
                                )),
                        subtotal NUMERIC(12,2) NOT NULL CHECK (subtotal >= 0),
                        delivery_fee NUMERIC(12,2) NOT NULL DEFAULT 0
                            CHECK (delivery_fee >= 0),
                        total_amount NUMERIC(12,2) NOT NULL CHECK (total_amount >= 0),
                        currency CHAR(3) NOT NULL DEFAULT 'NGN',
                        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE order_items (
                             order_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             order_id BIGINT NOT NULL
                                 REFERENCES orders(order_id) ON DELETE CASCADE,
                             product_id BIGINT NOT NULL REFERENCES products(product_id),
                             product_name_snapshot VARCHAR(180) NOT NULL,
                             sku_snapshot VARCHAR(60) NOT NULL,
                             unit_price_snapshot NUMERIC(12,2) NOT NULL
                                 CHECK (unit_price_snapshot >= 0),
                             quantity INTEGER NOT NULL CHECK (quantity > 0),
                             line_total NUMERIC(12,2) NOT NULL CHECK (line_total >= 0)
);

CREATE TABLE payments (
                          payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          order_id BIGINT NOT NULL REFERENCES orders(order_id),
                          provider_reference VARCHAR(100) NOT NULL UNIQUE,
                          payment_provider VARCHAR(40) NOT NULL,
                          amount NUMERIC(12,2) NOT NULL CHECK (amount > 0),
                          payment_status VARCHAR(20) NOT NULL
                              CHECK (payment_status IN (
                                                        'INITIATED', 'SUCCESS', 'FAILED', 'REVERSED'
                                  )),
                          paid_at TIMESTAMPTZ,
                          created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE shipments (
                           shipment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           order_id BIGINT NOT NULL UNIQUE REFERENCES orders(order_id),
                           carrier VARCHAR(80),
                           tracking_number VARCHAR(100) UNIQUE,
                           shipment_status VARCHAR(20) NOT NULL DEFAULT 'CREATED'
                               CHECK (shipment_status IN (
                                                          'CREATED', 'IN_TRANSIT', 'DELIVERED', 'FAILED', 'RETURNED'
                                   )),
                           shipped_at TIMESTAMPTZ,
                           delivered_at TIMESTAMPTZ
);

CREATE TABLE shipment_events (
                                 shipment_event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 shipment_id BIGINT NOT NULL
                                     REFERENCES shipments(shipment_id) ON DELETE CASCADE,
                                 event_status VARCHAR(30) NOT NULL,
                                 event_location VARCHAR(160),
                                 event_time TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                                 notes TEXT
);

CREATE TABLE reviews (
                         review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         customer_id BIGINT NOT NULL REFERENCES customers(customer_id),
                         product_id BIGINT NOT NULL REFERENCES products(product_id),
                         rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
                         review_text TEXT,
                         created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                         UNIQUE (customer_id, product_id)
);

CREATE TABLE coupons (
                         coupon_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         coupon_code VARCHAR(40) NOT NULL UNIQUE,
                         discount_percent NUMERIC(5,2) NOT NULL
                             CHECK (discount_percent > 0 AND discount_percent <= 100),
                         valid_from TIMESTAMPTZ NOT NULL,
                         valid_until TIMESTAMPTZ NOT NULL,
                         CHECK (valid_until > valid_from)
);

-- Range partitioning for order event history.
CREATE TABLE order_events (
                              event_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
                              order_id BIGINT NOT NULL REFERENCES orders(order_id),
                              event_type VARCHAR(40) NOT NULL,
                              event_payload JSONB NOT NULL DEFAULT '{}'::jsonb,
                              occurred_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                              PRIMARY KEY (event_id, occurred_at)
) PARTITION BY RANGE (occurred_at);

CREATE TABLE order_events_2026_01
    PARTITION OF order_events
    FOR VALUES FROM ('2026-01-01') TO ('2026-02-01');

CREATE TABLE order_events_2026_02
    PARTITION OF order_events
    FOR VALUES FROM ('2026-02-01') TO ('2026-03-01');

CREATE TABLE order_events_default
    PARTITION OF order_events DEFAULT;

-- Indexes
CREATE INDEX idx_products_category_active
    ON products(category_id, is_active);

CREATE INDEX idx_orders_customer_created
    ON orders(customer_id, created_at DESC);

CREATE INDEX idx_order_items_order
    ON order_items(order_id);

CREATE INDEX idx_payments_order_status
    ON payments(order_id, payment_status);

CREATE INDEX idx_shipment_events_shipment_time
    ON shipment_events(shipment_id, event_time DESC);

CREATE INDEX idx_products_attributes_gin
    ON products USING GIN(attributes);

COMMIT;